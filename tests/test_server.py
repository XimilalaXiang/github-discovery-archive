"""Tests for serve.py: health endpoint, headers, MIME types, 404, traversal."""

import json
import os
import sys
import threading
import unittest
import urllib.error
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import serve  # noqa: E402


class ServerTestCase(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.server = serve.make_server("127.0.0.1", 0)
        cls.host, cls.port = cls.server.server_address[:2]
        cls.thread = threading.Thread(target=cls.server.serve_forever, daemon=True)
        cls.thread.start()
        cls.base = f"http://{cls.host}:{cls.port}"

    @classmethod
    def tearDownClass(cls):
        cls.server.shutdown()
        cls.server.server_close()

    def get(self, path):
        try:
            with urllib.request.urlopen(self.base + path, timeout=5) as resp:
                return resp.status, dict(resp.headers), resp.read()
        except urllib.error.HTTPError as exc:
            return exc.code, dict(exc.headers), exc.read()


class HealthTests(ServerTestCase):
    def test_healthz_returns_ok_json(self):
        status, headers, body = self.get("/healthz")
        self.assertEqual(status, 200)
        self.assertIn("application/json", headers.get("Content-Type", ""))
        payload = json.loads(body)
        self.assertEqual(payload["status"], "ok")
        self.assertEqual(payload["service"], "github-discovery-archive")
        self.assertIn("time", payload)
        self.assertIn("dataset_present", payload)


class HeaderTests(ServerTestCase):
    def test_security_headers_present(self):
        _, headers, _ = self.get("/healthz")
        self.assertEqual(headers.get("X-Content-Type-Options"), "nosniff")
        self.assertEqual(headers.get("X-Frame-Options"), "DENY")
        self.assertEqual(headers.get("Referrer-Policy"), "strict-origin-when-cross-origin")
        self.assertIn("Content-Security-Policy", headers)
        self.assertIn("frame-ancestors 'none'", headers.get("Content-Security-Policy", ""))

    def test_content_security_policy_no_wildcard_scripts(self):
        _, headers, _ = self.get("/")
        csp = headers.get("Content-Security-Policy", "")
        self.assertIn("script-src 'self'", csp)


class StaticFileTests(ServerTestCase):
    def test_serves_index_html(self):
        status, headers, body = self.get("/")
        self.assertEqual(status, 200)
        self.assertIn("text/html", headers.get("Content-Type", ""))
        self.assertIn(b"<html", body.lower())

    def test_serves_css_with_charset(self):
        status, headers, _ = self.get("/assets/styles.css")
        self.assertEqual(status, 200)
        self.assertIn("text/css", headers.get("Content-Type", ""))
        self.assertIn("charset=utf-8", headers.get("Content-Type", ""))

    def test_serves_js_with_correct_type(self):
        status, headers, _ = self.get("/assets/app.js")
        self.assertEqual(status, 200)
        self.assertIn("javascript", headers.get("Content-Type", ""))

    def test_serves_dataset_json(self):
        status, headers, body = self.get("/data/projects.json")
        # Dataset is generated by sync.py; if absent, the route must 404 cleanly.
        if status == 200:
            self.assertIn("application/json", headers.get("Content-Type", ""))
            payload = json.loads(body)
            self.assertIn("projects", payload)
        else:
            self.assertEqual(status, 404)

    def test_missing_file_returns_404(self):
        status, headers, body = self.get("/does-not-exist.txt")
        self.assertEqual(status, 404)
        self.assertIn("application/json", headers.get("Content-Type", ""))
        self.assertEqual(json.loads(body)["error"], "not found")

    def test_head_request_has_no_body(self):
        req = urllib.request.Request(self.base + "/healthz", method="HEAD")
        with urllib.request.urlopen(req, timeout=5) as resp:
            self.assertEqual(resp.status, 200)
            self.assertEqual(resp.read(), b"")
            self.assertGreater(int(resp.headers.get("Content-Length", "0")), 0)


class PathSafetyTests(ServerTestCase):
    def test_blocks_parent_traversal(self):
        status, _, _ = self.get("/../sync.py")
        self.assertEqual(status, 404)

    def test_blocks_encoded_traversal(self):
        status, _, _ = self.get("/%2e%2e/%2e%2e/etc/passwd")
        self.assertEqual(status, 404)

    def test_does_not_serve_project_source(self):
        # serve.py / sync.py live outside web/, so must not be reachable.
        for path in ("/sync.py", "/serve.py", "/tests/test_sync.py"):
            status, _, _ = self.get(path)
            self.assertEqual(status, 404, msg=f"{path} should be 404")


if __name__ == "__main__":
    unittest.main()
